"""libfuri (spec R5.2): PNG icons -> const C data (flash, 0 B RAM).

    python3 -I tools/icons.py assets/icons src/gui/assets_icons.c include/assets_icons.h

Same conversion as the stock firmware's scripts/flipper/assets/icon.py
(PIL convert("1"), inverted: a dark pixel is a set bit; XBM rows, LSB
first) and the same Icon layout (gui/icon_i.h). Frames are stored
uncompressed (first byte 0x00): no heatshrink decoder and no RAM buffer
to decompress into. A directory of frame_NN.png files plus frame_rate is
an animated icon (A_<name>), a single PNG a still one (I_<name>).
The generated files are checked in; PIL is needed only to regenerate."""
import os
import sys

from PIL import Image, ImageOps


def xbm(path):
    with Image.open(path) as im:
        bw = ImageOps.invert(im.convert("1"))
        w, h = bw.size
        px = bw.load()
        out = bytearray()
        for y in range(h):
            for xb in range(0, w, 8):
                b = 0
                for i in range(8):
                    if xb + i < w and px[xb + i, y]:
                        b |= 1 << i
                out.append(b)
        return w, h, bytes([0]) + bytes(out)


def carray(name, data):
    s = "static const uint8_t %s[] = {" % name
    for i, b in enumerate(data):
        if i % 12 == 0:
            s += "\n    "
        s += "0x%02x," % b
    return s + "\n};\n"


def main(src, cout, hout):
    names = sorted(os.listdir(src))
    c = ["/* SPDX-License-Identifier: GPL-3.0-or-later\n"
         " * Generated by tools/icons.py from assets/icons (stock firmware\n"
         " * assets/icons, GPL-3.0). Do not edit. */\n",
         "#include <gui/icon_i.h>\n#include <assets_icons.h>\n\n"]
    h = ["/* SPDX-License-Identifier: GPL-3.0-or-later\n"
         " * Generated by tools/icons.py. Do not edit. */\n",
         "#pragma once\n#include <gui/icon.h>\n\n"]
    for n in names:
        p = os.path.join(src, n)
        if os.path.isdir(p):
            frames = sorted(f for f in os.listdir(p) if f.endswith(".png"))
            with open(os.path.join(p, "frame_rate")) as f:
                rate = int(f.read().strip())
            sym = "A_" + n
            refs = []
            for i, fr in enumerate(frames):
                w, hh, d = xbm(os.path.join(p, fr))
                c.append(carray("_%s_%d" % (sym, i), d))
                refs.append("_%s_%d" % (sym, i))
        elif n.endswith(".png"):
            sym = "I_" + n[:-4]
            w, hh, d = xbm(p)
            c.append(carray("_%s_0" % sym, d))
            refs = ["_%s_0" % sym]
            rate = 0
        else:
            continue
        c.append("static const uint8_t* const _%s[] = {%s};\n" % (sym, ", ".join(refs)))
        c.append("const Icon %s = {.width = %d, .height = %d, .frame_count = %d, "
                 ".frame_rate = %d, .frames = _%s};\n\n" % (sym, w, hh, len(refs), rate, sym))
        h.append("extern const Icon %s;\n" % sym)
    with open(cout, "w") as f:
        f.write("".join(c))
    with open(hout, "w") as f:
        f.write("".join(h))


if __name__ == "__main__":
    main(*sys.argv[1:4])
