#!/usr/bin/env python3
"""Write gzbuild.h (spec J.2): GZ_BUILD, the build id after the release
number ("" at a release tag, else "+N.gHASH", "-dirty" for uncommitted
changes), and GZ_BUILD_DATE, the date of the commit (not of the build, so
a rebuild of the same tree gives the same image).

Usage: gzbuild.py out.h     (rewritten only when its contents change)"""
import subprocess
import sys


def git(*args):
    try:
        return subprocess.run(["git", *args], capture_output=True, text=True,
                              check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return ""


build = ""
d = git("describe", "--tags", "--match", "v*", "--long", "--dirty")
if d:
    dirty = d.endswith("-dirty")
    if dirty:
        d = d[:-len("-dirty")]
    tag, n, h = d.rsplit("-", 2)
    if n != "0" or dirty:
        build = f"+{n}.{h}" + ("-dirty" if dirty else "")
date = git("log", "-1", "--format=%cs")
text = (f"/* generated by tools/gzbuild.py - not in git */\n"
        f"#define GZ_BUILD\t\"{build}\"\n"
        f"#define GZ_BUILD_DATE\t\"{date}\"\n")
out = sys.argv[1]
try:
    old = open(out).read()
except OSError:
    old = None
if old != text:
    with open(out, "w") as f:
        f.write(text)
