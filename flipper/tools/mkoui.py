#!/usr/bin/env python3
"""mkoui - the camfind vendor table (spec R9.1.2) from the IEEE registry.

Usage: mkoui.py oui.csv vendors.txt cfoui.c

oui.csv is the public IEEE MA-L registry (https://standards-oui.ieee.org/
oui/oui.csv; not in the repo).  vendors.txt names the makers to keep.
cfoui.c holds, per vendor, its OUIs sorted (3 bytes each) and a vendor
table with the kind, the first entry and the count: lookups do a binary
search per vendor.  The output is checked in, so builds need no network.
"""
import csv
import re
import sys

csvpath, listpath, out = sys.argv[1:]
vendors = []
for line in open(listpath, encoding="utf-8"):
    if not line.strip() or line.startswith("#"):
        continue
    kind, name, pat = line.rstrip("\n").split(None, 2)
    if kind not in ("camera", "module"):
        sys.exit(f"mkoui: {kind}: camera or module")
    vendors.append((kind, name, re.compile(pat, re.I), []))

with open(csvpath, encoding="utf-8", errors="replace", newline="") as f:
    rows = csv.reader(f)
    next(rows)
    for reg, hexa, org, *_ in rows:
        if reg != "MA-L" or not re.fullmatch(r"[0-9A-F]{6}", hexa):
            continue
        for v in vendors:
            if v[2].search(org):
                v[3].append(int(hexa, 16))
                break                       # the first pattern wins

with open(out, "w") as f:
    f.write("/* camfind vendor table, generated by tools/mkoui.py from the IEEE\n"
            " * registry and apps/camfind/vendors.txt - do not edit (R9.1.2). */\n"
            "#include \"cfcore.h\"\n\nconst unsigned char cf_oui[] = {\n")
    first = 0
    table = []
    for kind, name, _, ouis in vendors:
        ouis = sorted(set(ouis))
        f.write(f"\t/* {name}: {len(ouis)} */\n")
        for i in range(0, len(ouis), 4):
            f.write("\t" + " ".join(f"0x{o >> 16:02x},0x{o >> 8 & 255:02x},"
                                     f"0x{o & 255:02x}," for o in ouis[i:i + 4])
                    + "\n")
        table.append((name, kind, first, len(ouis)))
        first += len(ouis)
    f.write("};\n\nconst struct cf_vendor cf_vendors[] = {\n")
    for name, kind, first, n in table:
        k = "CF_CAMERA" if kind == "camera" else "CF_IOT"
        f.write(f"\t{{ \"{name}\", {k}, {first}, {n} }},\n")
    f.write("};\n\nconst int cf_nvendors = sizeof(cf_vendors) / sizeof(cf_vendors[0]);\n")
print(f"mkoui: {first} OUIs of {len(table)} vendors, {first * 3} bytes")
