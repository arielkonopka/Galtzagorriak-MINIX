#!/usr/bin/env python3
"""A 128x64 picture to the C array bootscreen draws (issue #399).

Usage: mkbootart.py art/galtzagorri-fix.png gui/bootart.h [SYMBOL]

SYMBOL names the array (default bootart_fb).  An output ending in .c gets a
non-static array (for the HAL, charge_fb); .h a static one.

No scaling or dither: the picture is already 1 bit and 128x64.  Same
convention as mksplash.py: a pixel below 128 is dark, a set bit is dark,
ST7567 page layout (bit n of byte page*128+x = row page*8+n)."""
import sys

from PIL import Image

W, H = 128, 64


def main():
    src, out = sys.argv[1], sys.argv[2]
    sym = sys.argv[3] if len(sys.argv) > 3 else "bootart_fb"
    img = Image.open(src).convert("L")
    if img.size != (W, H):
        sys.exit("%s: %dx%d, need %dx%d" % (src, *img.size, W, H))
    fb = bytearray(W * H // 8)
    for y in range(H):
        for x in range(W):
            if img.getpixel((x, y)) < 128:
                fb[(y >> 3) * W + x] |= 1 << (y & 7)
    with open(out, "w") as f:
        f.write("/* Generated by flipper/tools/mkbootart.py from %s - do not edit. */\n" % src)
        f.write("%sconst unsigned char %s[%d] = {\n"
                % ("" if out.endswith(".c") else "static ", sym, len(fb)))
        for i in range(0, len(fb), 16):
            f.write("  " + ",".join("0x%02x" % b for b in fb[i:i + 16]) + ",\n")
        f.write("};\n")


main()
