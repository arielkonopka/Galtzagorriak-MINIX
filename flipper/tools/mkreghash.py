#!/usr/bin/env python3
"""Write the C list of the shipped region tables' SHA-256 (spec Q.3, RQ.5).

Usage: mkreghash.py OUT.c FILE.reg ...

Each entry is the two-letter code (from the file name) and the SHA-256 of
the file as shipped: 34 B per table, const, so it stays in flash (0 B RAM).
`region set` hashes the card's file and its Base: file; a hash not in the
list is a custom table and needs -f.
"""
import hashlib
import os
import sys


def main(argv):
    if len(argv) < 2:
        sys.stderr.write(__doc__)
        return 2
    out, files = argv[0], sorted(argv[1:], key=os.path.basename)
    lines = [
        "/* Generated by flipper/tools/mkreghash.py: do not edit (RQ.5). */",
        '#include "modem.h"',
        "const struct mdm_rghash mdm_rg_shipped[] = {",
    ]
    for f in files:
        base = os.path.basename(f)
        cc = base[:-4]
        if not (base.endswith(".reg") and len(cc) == 2 and cc.isupper()):
            sys.stderr.write("mkreghash: %s: not CC.reg\n" % f)
            return 1
        with open(f, "rb") as fp:
            h = hashlib.sha256(fp.read()).digest()
        lines.append('\t{ "%s", { %s } },' % (
            cc, ",".join("0x%02x" % b for b in h)))
    lines.append("};")
    lines.append("const int mdm_rg_nshipped = %d;" % len(files))
    tmp = out + ".tmp"
    with open(tmp, "w") as fp:
        fp.write("\n".join(lines) + "\n")
    os.replace(tmp, out)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
