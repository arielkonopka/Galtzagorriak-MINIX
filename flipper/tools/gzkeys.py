#!/usr/bin/env python3
"""Write gzkeys.h for gzupdate (spec RS.6, T33a part 3): the public keys
atea's two slots will hold, as a C initializer.  Each argument is a file
with 64 hex digits (keys/release.pub, ~/.config/galtzagorriak/update.pub,
UPDATE_TESTKEY); at most 2 are used, in that order.  The file is rewritten
only when it changes, so a build without key changes relinks nothing.

Usage: gzkeys.py OUT.h [KEYFILE...]"""
import os
import re
import sys

out, files = sys.argv[1], sys.argv[2:]
keys = []
for p in files:
    t = open(p).read().strip()
    if not re.fullmatch(r"[0-9a-fA-F]{64}", t):
        sys.exit(f"gzkeys: {p}: not a public key (64 hex digits)")
    k = bytes.fromhex(t)
    if k not in keys:
        keys.append(k)
if len(keys) > 2:
    print(f"gzkeys: {len(keys)} keys, atea has 2 slots: using the first 2")
    keys = keys[:2]
body = ",\n".join("\t{ " + ", ".join(f"0x{b:02x}" for b in k) + " }"
                  for k in keys) or "\t{ 0 }"
text = ("/* gzkeys.h - generated by tools/gzkeys.py: the trusted public keys "
        "(RS.6) */\n"
        f"#define GZ_NKEYS\t{len(keys)}\n#define GZ_KEYS\t{{ \\\n" +
        body.replace("\n", " \\\n") + " \\\n}\n")
if not os.path.exists(out) or open(out).read() != text:
    with open(out, "w") as f:
        f.write(text)
