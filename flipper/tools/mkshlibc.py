#!/usr/bin/env python3
"""The shared libraries in flash (spec Phase 2b, R2b.9; <minix/shlibc.h>):
the shared libc, and libfuri + libapp (the "furi" library, R5.2, 7b).

  mkshlibc.py tab EXPORTS OUT.S [--furi|--berry]
      The header and the entry table (one .word per exported function, in
      the frozen order of EXPORTS), plus (libc only) the library's own
      copies of the variables crtso defines for a static program.  Linked
      first.  --furi, --berry: the furi or Berry library's magic (R7c.1,
      ld/shberry.ld), no crtso variables.
  mkshlibc.py image LIB.elf EXPORTS OUT.bin OUT.json STUBS.S SYMS.ld
                    [--dep LIBC.json --name SHFURI --max BYTES]
      LIB.elf (ld/shlibc.ld or ld/shfuri.ld, -q) -> the flash image with
      its build id filled in; OUT.json for tools/elf2mnx.py (the area's
      initial contents and which words in it hold data addresses); STUBS.S,
      one weak 12-byte stub per function; SYMS.ld, the library's variables
      at their fixed places in the area, for the program's link.
      --dep: a library linked on top of the shared libc (ld/shfuri.ld): its
      area follows the libc area, it may hold the libc's flash addresses,
      its id covers the libc's, and only the functions in EXPORTS are
      exported (the others are its own: libgcc, static libc members).
  mkshlibc.py exports LIBC.elf
      Print the global functions of a libc build, sorted (to start an
      EXPORTS file; after that it only grows at the end).

EXPORTS is frozen for an ABI: a name keeps its slot, new functions go at
the end, and a name may not be removed without a new GZ_ABI (spec J.3).
"""
import json
import os
import re
import struct
import sys
import zlib

A_DATA_LINK = 0x10000000
MAGIC = 0x434C5A47          # "GZLC"
MAGIC_FURI = 0x464C5A47     # "GZLF"
MAGIC_BERRY = 0x424C5A47    # "GZLB"
MAGICS = {MAGIC: "GZLC", MAGIC_FURI: "GZLF", MAGIC_BERRY: "GZLB"}
HDR = 24                    # bytes before sh_slot[]
SHN_UNDEF, SHN_ABS = 0, 0xFFF1
R_ARM_ABS32, R_ARM_TARGET1 = 2, 38

with open(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                       "../../include/minix/gzversion.h")) as _f:
    GZ_ABI = int(re.search(r"#define\s+GZ_ABI\s+(\d+)", _f.read()).group(1))

# Defined by crtso.S for a static program; in the library for a shared one
# (crtso then sets _brksize to the program's own _end).
CRT_VARS = ("_penvp", "_brksize")


def read_exports(path):
    names = []
    for line in open(path):
        line = line.split("#", 1)[0].strip()
        if line:
            names.append(line)
    if len(set(names)) != len(names):
        sys.exit(f"{path}: a name is listed twice")
    return names


class Elf:
    def __init__(self, path):
        self.path = path
        e = self.e = open(path, "rb").read()
        if e[:4] != b"\x7fELF" or e[4] != 1 or e[5] != 1:
            sys.exit(f"{path}: not a 32-bit little-endian ELF")
        (_, _, _, _, _, shoff, _, _, _, _, shentsize, shnum,
         shstrndx) = struct.unpack_from("<HHIIIIIHHHHHH", e, 16)
        self.sh = [struct.unpack_from("<IIIIIIIIII", e, shoff + i * shentsize)
                   for i in range(shnum)]
        strtab = self.sh[shstrndx]
        self.names = [self.cstr(strtab[4] + s[0]) for s in self.sh]
        self.secs = {n: s for n, s in zip(self.names, self.sh)}
        self.syms = []
        st = self.secs.get(".symtab")
        if st:
            stro = self.sh[st[6]][4]
            for i in range(st[5] // 16):
                nm, val, size, info, other, shndx = struct.unpack_from(
                    "<IIIBBH", e, st[4] + i * 16)
                self.syms.append((self.cstr(stro + nm), val, size,
                                  info >> 4, info & 15, shndx))

    def cstr(self, off):
        return self.e[off:self.e.index(b"\0", off)].decode()

    def bytes_of(self, name):
        s = self.secs[name]
        return self.e[s[4]:s[4] + s[5]] if s[1] != 8 else bytes(s[5])

    def relocs(self, target):
        """(offset, type, symbol index) of the -q relocations of target."""
        out = []
        for i, s in enumerate(self.sh):
            if s[1] != 9 or self.names[s[7]] != target:
                continue
            for k in range(s[5] // 8):
                off, info = struct.unpack_from("<II", self.e, s[4] + k * 8)
                out.append((off, info & 0xFF, info >> 8))
        return out


def tab(exports, out, magic=MAGIC):
    names = read_exports(exports)
    furi = magic != MAGIC
    with open(out, "w") as f:
        f.write(f"""/* Generated by tools/mkshlibc.py from {os.path.basename(exports)}:
 * the shared libc's header and entry table (<minix/shlibc.h>). */
	.syntax	unified
	.section .shlibc.hdr, "a", %progbits
	.p2align 2
	.global	_shlibc_hdr
_shlibc_hdr:
	.word	{magic:#x}		@ sh_magic {MAGICS[magic]}
	.short	{GZ_ABI}, {len(names)}		@ sh_abi, sh_nslot
	.word	0			@ sh_id: filled in by mkshlibc.py image
	.word	_shlibc_size		@ sh_size
	.word	_shlibc_area		@ sh_area
	.word	0			@ sh_resv
""")
        for n in names:
            f.write(f"\t.word\t{n}\n")
        if furi:
            return
        f.write("\n\t.data\n\t.p2align 2\n")
        for v in CRT_VARS:
            f.write(f"\t.global\t{v}\n{v}:\t.word\t0\n")


def image(elf_path, exports, out_bin, out_json, out_stubs, out_syms,
          dep_json=None, name="SHLIBC", maxsize=0x10000):
    elf = Elf(elf_path)
    names = read_exports(exports)
    dep = None
    if dep_json:
        with open(dep_json) as f:
            dep = json.load(f)
        dep_names = set(read_exports(dep["exports"]))
        both = sorted(set(names) & dep_names)
        if both:
            sys.exit(f"{exports}: {' '.join(both)} also in the shared libc")
    # The area starts after the libc area for a library on top of libc.
    start = dep["area"] if dep else 0
    astart = A_DATA_LINK + start
    text = elf.secs[".text"]
    base, tsize = text[3], text[5]
    tlo, thi = base, base + tsize
    parts = [n for n in (".got", ".data") if n in elf.secs and elf.secs[n][5]]
    bss = elf.secs.get(".bss")
    area_end = max([elf.secs[n][3] + elf.secs[n][5] for n in parts]
                   + ([bss[3] + bss[5]] if bss else [astart]) + [astart])
    area = area_end - astart
    dend = max([elf.secs[n][3] + elf.secs[n][5] for n in parts] + [astart])
    full = bytearray(dend - A_DATA_LINK)
    for n in parts:
        s = elf.secs[n]
        if s[3] < A_DATA_LINK:
            sys.exit(f"{elf_path}: {n} below A_DATA_LINK")
        full[s[3] - A_DATA_LINK:s[3] - A_DATA_LINK + s[5]] = elf.bytes_of(n)
    if any(full[:start]):
        sys.exit(f"{elf_path}: data inside the libc area")
    tmpl = full[start:]

    def kind(v):
        if v == 0 or tlo <= v < thi:
            return "abs"                # null, or the library's flash
        if dep and dep["base"] <= v < dep["base"] + dep["size"]:
            return "abs"                # the shared libc's flash
        if A_DATA_LINK <= v <= area_end:
            return "data"               # its area (or the libc's)
        return None

    # Words of the area that hold data addresses: exec adds the data base.
    # (Offsets from the start of the data segment.)
    relocs = set()
    got = elf.secs.get(".got")
    if got:
        for off in range(max(got[3], astart) - A_DATA_LINK,
                         got[3] - A_DATA_LINK + got[5], 4):
            v = struct.unpack_from("<I", full, off)[0]
            k = kind(v)
            if k is None:
                sys.exit(f"{elf_path}: GOT word {off:#x} = {v:#x} is neither "
                         "in the library nor in its area")
            if k == "data":
                relocs.add(off)
    for target in (".data",):
        for off, rtype, rsym in elf.relocs(target):
            if rtype not in (R_ARM_ABS32, R_ARM_TARGET1):
                if rtype == 0:
                    continue
                sys.exit(f"{elf_path}: relocation type {rtype} in {target}")
            off -= A_DATA_LINK
            v = struct.unpack_from("<I", full, off)[0]
            k = kind(v)
            if k is None:
                sys.exit(f"{elf_path}: data word {off:#x} = {v:#x} is neither "
                         "in the library nor in its area")
            if k == "data":
                relocs.add(off)
    # Words of the text and of the area that hold the library's own flash
    # addresses (the constant tables, the entry table, GOT entries of its
    # functions and strings): what would have to change if the library
    # were written somewhere else than its link address (#433: placed at
    # install time).  Counted for PORTING.md, listed in the json.
    trelocs, arelocs = [], []
    if got:
        for off in range(max(got[3], astart) - A_DATA_LINK,
                         got[3] - A_DATA_LINK + got[5], 4):
            v = struct.unpack_from("<I", full, off)[0]
            if tlo <= v < thi:
                arelocs.append(off)
    for target in (".text",):
        for off, rtype, rsym in elf.relocs(target):
            if rtype in (R_ARM_ABS32, R_ARM_TARGET1) and base <= off < base + HDR:
                continue                # sh_size, sh_area: link-time values
            if rtype in (R_ARM_ABS32, R_ARM_TARGET1):
                v = struct.unpack_from("<I", elf.e, text[4] + off - base)[0]
                if tlo <= v < thi:
                    trelocs.append(off - base)
                if kind(v) == "data":
                    sys.exit(f"{elf_path}: the text at {off:#x} holds a data "
                             "address (an object not compiled -fpic?)")

    # The exported functions: every global function in the image must have
    # a slot (a library on top of libc: only those listed are exported),
    # and the slots must be where tab put them.
    funcs, data = {}, {}
    for nm, val, size, bind, typ, shndx in elf.syms:
        if bind not in (1, 2) or shndx in (SHN_UNDEF,) or not nm:
            continue
        if nm.startswith("_shlibc_"):
            continue
        if typ == 2:                                   # STT_FUNC
            funcs[nm] = val
        elif shndx == SHN_ABS:
            continue
        else:
            data[nm] = val
    missing = sorted(set(funcs) - set(names))
    if missing and not dep:
        sys.exit(f"{elf_path}: functions without a slot: {' '.join(missing)}\n"
                 f"  append them to {exports} (never insert or reorder: the "
                 "order is the ABI)")
    gone = [n for n in names if n not in funcs]
    if gone:
        sys.exit(f"{elf_path}: {exports} lists {' '.join(gone)}, which the "
                 "library no longer has: that changes the ABI (spec J.3)")
    img = bytearray(elf.bytes_of(".text"))
    magic, abi, nslot = struct.unpack_from("<IHH", img, 0)
    if (magic not in ((MAGIC_FURI, MAGIC_BERRY) if dep else (MAGIC,))
            or nslot != len(names)):
        sys.exit(f"{elf_path}: the header is not first in the text")
    for i, n in enumerate(names):
        slot = struct.unpack_from("<I", img, HDR + 4 * i)[0]
        if slot != funcs[n] | 1:
            sys.exit(f"{elf_path}: slot {i} is not {n}")
    if struct.unpack_from("<I", img, 16)[0] != area:
        sys.exit(f"{elf_path}: sh_area {struct.unpack_from('<I', img, 16)[0]}"
                 f" is not {area}")
    if len(img) > maxsize:
        sys.exit(f"{elf_path}: {len(img)} bytes, more than {name}_MAX "
                 f"({maxsize})")

    # The build id covers the code and the area's initial contents: a
    # program carries the latter, so it fits this build only.  A library
    # on top of libc also depends on the libc build (where its area
    # starts, the libc functions it calls).
    lid = zlib.crc32(bytes(tmpl), zlib.crc32(bytes(img))) & 0xFFFFFFFF
    if dep:
        lid = zlib.crc32(struct.pack("<II", dep["id"], start), lid) & 0xFFFFFFFF
    if lid in (0, 0xFFFFFFFF):
        lid ^= 0x5A5A5A5A
    struct.pack_into("<I", img, 8, lid)
    img += b"\xff" * (-len(img) % 8)            # whole flash double words
    with open(out_bin, "wb") as f:
        f.write(img)

    slots = {n: base + HDR + 4 * i for i, n in enumerate(names)}
    info = {
        "base": base, "size": tsize, "id": lid, "area": area, "start": start,
        "exports": os.path.abspath(exports),
        "template": bytes(tmpl).hex(), "relocs": sorted(relocs),
        "text_self": sorted(set(trelocs)), "area_self": sorted(arelocs),
    }
    with open(out_json, "w") as f:
        json.dump(info, f, indent=0)
        f.write("\n")

    sect = name.lower()
    with open(out_stubs, "w") as f:
        f.write("/* Generated by tools/mkshlibc.py: one stub per function "
                f"of {os.path.basename(exports)}.\n * Weak, so that a "
                "program's own definition wins, as with a static library. "
                "*/\n\t.syntax\tunified\n\t.thumb\n")
        for n in names:
            f.write(f"""
	.section .text.{sect}.{n}, "ax", %progbits
	.p2align 2
	.weak	{n}
	.type	{n}, %function
	.thumb_func
{n}:
	ldr.w	ip, 1f
	ldr.w	pc, [ip]
1:	.word	{slots[n]:#x}
	.size	{n}, . - {n}
""")
    with open(out_syms, "w") as f:
        f.write("/* Generated by tools/mkshlibc.py: the variables of "
                f"{os.path.basename(exports)}'s library\n * (in its area at "
                "r9, or in its flash), for the program's link. */\n")
        f.write(f"{name}_AREA = {area:#x};\n")
        for n in sorted(data):
            f.write(f"PROVIDE({n} = {data[n]:#x});\n")
    print(f"  {name}: {len(img)} bytes at {base:#x}, {len(names)} "
          f"functions, {len(data)} variables, area {area} bytes at "
          f"+{start} ({len(relocs)} relocated), id {lid:#010x}; own flash "
          f"addresses: {len(set(trelocs))} words of text, {len(arelocs)} of "
          "the area")


def exports(elf_path):
    elf = Elf(elf_path)
    for n in sorted({nm for nm, val, size, bind, typ, shndx in elf.syms
                     if bind in (1, 2) and typ == 2 and shndx != SHN_UNDEF}):
        print(n)


def main():
    args = sys.argv[1:]
    opts = {}
    while len(args) >= 2 and args[-2] in ("--dep", "--name", "--max"):
        opts[args[-2][2:]] = args[-1]
        del args[-2:]
    if (args[-1:] in (["--furi"], ["--berry"]) and args[0] == "tab"
            and len(args) == 4):
        tab(args[1], args[2],
            MAGIC_FURI if args[-1] == "--furi" else MAGIC_BERRY)
    elif len(args) == 3 and args[0] == "tab":
        tab(*args[1:])
    elif len(args) == 7 and args[0] == "image":
        image(*args[1:], dep_json=opts.get("dep"),
              name=opts.get("name", "SHLIBC"),
              maxsize=int(opts.get("max", "0x10000"), 0))
    elif len(sys.argv) == 3 and sys.argv[1] == "exports":
        exports(sys.argv[2])
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
