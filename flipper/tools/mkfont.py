#!/usr/bin/env python3
"""Convert an X11 PCF bitmap font (e.g. misc-fixed 4x6, public domain) into a
C table for the MINIX/Flipper framebuffer console.

Usage: mkfont.py font.pcf.gz WIDTH HEIGHT > font.c
Each glyph (ASCII 32..126) is HEIGHT bytes; bit 7 is the leftmost pixel."""
import gzip, io, sys
from PIL import PcfFontFile

path, w, h = sys.argv[1], int(sys.argv[2]), int(sys.argv[3])
data = gzip.open(path).read() if path.endswith('.gz') else open(path, 'rb').read()
font = PcfFontFile.PcfFontFile(io.BytesIO(data))
# font.glyph[ch] = ((dx, dy), (x0, y0, x1, y1) dst box rel. to baseline, src box, image)
ascent = max(-g[1][1] for g in font.glyph if g)
out = [f"/* Generated by flipper/tools/mkfont.py from {path.split('/')[-1]} (public domain X11 misc-fixed). */",
       f"#define FONT_W {w}", f"#define FONT_H {h}",
       f"const unsigned char font_{w}x{h}[95][{h}] = {{"]
for ch in range(32, 127):
    rows = [0] * h
    g = font.glyph[ch]
    if g:
        _, (x0, y0, x1, y1), _, im = g
        for y in range(im.size[1]):
            for x in range(im.size[0]):
                if im.getpixel((x, y)):
                    px, py = x0 + x, ascent + y0 + y
                    if 0 <= px < w and 0 <= py < h:
                        rows[py] |= 0x80 >> px
    out.append("  {" + ",".join(f"0x{r:02x}" for r in rows) + "}, /* " + repr(chr(ch)) + " */")
out.append("};")
print("\n".join(out))
