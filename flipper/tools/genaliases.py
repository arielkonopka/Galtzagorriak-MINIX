#!/usr/bin/env python3
"""Generate ARM versions of MINIX's src/lib/syscall/*.s alias stubs.

Each of those x86 files is just

	.define	_foo
_foo:	jmp	__foo

i.e. the public name foo() jumps to the library's _foo().  This emits the
same for Thumb-2, one function per section so --gc-sections drops unused
ones.

Usage: genaliases.py src/lib/syscall out.S
"""
import os
import re
import sys

srcdir, out = sys.argv[1:]
pairs = []
for name in sorted(os.listdir(srcdir)):
    if not name.endswith(".s"):
        continue
    with open(os.path.join(srcdir, name)) as f:
        text = f.read()
    m = re.search(r"^(_\w+):\s*\n\s*jmp\s+(_\w+)", text, re.M)
    if not m:
        raise SystemExit(f"{name}: unexpected format")
    # ACK prefixes C names with '_'; gcc does not.
    pairs.append((m.group(1)[1:], m.group(2)[1:]))

lines = ["/* Generated by flipper/tools/genaliases.py - do not edit. */",
         "\t.syntax\tunified", "\t.thumb"]
for public, target in pairs:
    lines += [f"\t.section .text.{public},\"ax\",%progbits",
              f"\t.global\t{public}", f"\t.type\t{public}, %function",
              "\t.thumb_func", f"{public}:", f"\tb.w\t{target}"]
with open(out, "w") as f:
    f.write("\n".join(lines) + "\n")
print(f"  {len(pairs)} aliases -> {out}")
