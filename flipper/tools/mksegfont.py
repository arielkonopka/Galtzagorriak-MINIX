#!/usr/bin/env python3
"""mksegfont.py - a seven-segment font for the clock: the digits 0-9, ':'
and '-' in cells of 16x24, drawn as segments with pointed ends on the pixel
grid (our own shapes: no font file is used).

Usage: python3 -I mksegfont.py > ../gui/segfont.h      (needs Pillow)
       python3 -I mksegfont.py --png preview.png        (to look at it)

Each glyph is 24 rows of 16 bits; bit 15 is the leftmost pixel.  576 B of
flash for the 12 glyphs, no RAM.  The user chose this one of six
candidates on 2026-11-27 (cells of 8x16, 16x16, 16x24 and 16x32, ours
and a rasterised free font)."""
import sys
from PIL import Image, ImageDraw

W, H, T = 16, 24, 3          # cell, and the segments' thickness
PAD, GAP = 1, 1              # blank columns at the sides; gap at a segment's ends
CH = "0123456789:-"
DIGITS = {'0': 'abcdef', '1': 'bc', '2': 'abged', '3': 'abgcd', '4': 'fgbc',
          '5': 'afgcd', '6': 'afgedc', '7': 'abc', '8': 'abcdefg', '9': 'abfgcd'}


def glyphs():
    left, right, top, bottom = PAD, W - 1 - PAD, 0, H - 1
    mid = (H - 1) / 2.0
    h = (T - 1) / 2.0

    def hseg(yc):            # a horizontal segment centred on row yc
        x0, x1, k = left + T // 2 + GAP, right - T // 2 - GAP, T / 2.0
        return [(x0, yc), (x0 + k, yc - k), (x1 - k, yc - k), (x1, yc),
                (x1 - k, yc + k), (x0 + k, yc + k)]

    def vseg(xc, y0, y1):    # a vertical one centred on column xc
        k = T / 2.0
        y0 += GAP
        y1 -= GAP
        return [(xc, y0), (xc + k, y0 + k), (xc + k, y1 - k), (xc, y1),
                (xc - k, y1 - k), (xc - k, y0 + k)]

    seg = {'a': hseg(top + h), 'g': hseg(mid), 'd': hseg(bottom - h),
           'f': vseg(left + h, top + h, mid), 'b': vseg(right - h, top + h, mid),
           'e': vseg(left + h, mid, bottom - h), 'c': vseg(right - h, mid, bottom - h)}
    out = {}
    for c, ss in DIGITS.items():
        im = Image.new("1", (W, H), 0)
        d = ImageDraw.Draw(im)
        for s in ss:
            d.polygon(seg[s], fill=1)
        out[c] = im
    im = Image.new("1", (W, H), 0)          # the colon: two square dots
    d = ImageDraw.Draw(im)
    r, cx = max(1, T // 2), W // 2
    for cy in (H * 0.32, H * 0.68):
        d.rectangle([cx - r, int(cy) - r, cx + r - (T % 2 == 0),
                     int(cy) + r - (T % 2 == 0)], fill=1)
    out[':'] = im
    im = Image.new("1", (W, H), 0)          # the minus: segment g alone
    ImageDraw.Draw(im).polygon(seg['g'], fill=1)
    out['-'] = im
    return out


def rows(im):
    return [sum((1 << (W - 1 - x)) for x in range(W) if im.getpixel((x, y)))
            for y in range(H)]


def main():
    g = glyphs()
    if sys.argv[1:2] == ["--png"]:
        z = 4
        scr = Image.new("L", (128, 64), 255)
        for i, c in enumerate("21:37"):
            for y in range(H):
                for x in range(W):
                    if g[c].getpixel((x, y)):
                        scr.putpixel((24 + i * W + x, 10 + y), 0)
        scr.resize((128 * z, 64 * z), Image.NEAREST).save(sys.argv[2])
        return 0
    print("/* Generated by flipper/tools/mksegfont.py: the clock's seven-segment")
    print(" * digits: 0-9, ':' (index 10) and '-' (11), %dx%d, bit 15 the leftmost" % (W, H))
    print(" * pixel.")
    print(" * Our own shapes; do not edit, run the tool. */")
    print("#define SEG_W %d" % W)
    print("#define SEG_H %d" % H)
    print("static const unsigned short font_seg[%d][SEG_H] = {" % len(CH))
    for c in CH:
        r = rows(g[c])
        print("  { /* '%s' */" % c)
        for i in range(0, H, 8):
            print("    " + ",".join("0x%04x" % v for v in r[i:i + 8]) + ",")
        print("  },")
    print("};")
    return 0


if __name__ == "__main__":
    sys.exit(main())
